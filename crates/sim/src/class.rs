#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum TargetRule {
    /// Requires a living hostile target in range.
    Enemy,
    /// Friendly target in range; falls back to self when none/hostile is selected.
    Ally,
    /// Always the caster.
    SelfOnly,
}

/// Broad ability category, used by the AI and for effects colouring.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Category {
    Damage,
    Heal,
    Threat,
    Defensive,
    Interrupt,
    Control,
    Utility,
}

#[derive(Debug, Clone, Copy, PartialEq)]
pub enum Effect {
    /// Direct damage with a threat multiplier.
    Damage {
        amount: f32,
        threat_mult: f32,
        kind: HitKind,
    },
    /// Damage to every engaged enemy within `radius` of the caster.
    AoeDamage {
        amount: f32,
        radius: f32,
        threat_mult: f32,
    },
    Heal {
        amount: f32,
    },
    /// Heal over time: `total` spread over `duration` seconds, ticking each second.
    Hot {
        total: f32,
        duration: f32,
    },
    /// Damage over time; bleeds ignore armor.
    Dot {
        total: f32,
        duration: f32,
        ignores_armor: bool,
    },
    /// Damage absorption shield; also applies Weakened Soul (no re-shield) for `lockout`.
    Absorb {
        amount: f32,
        duration: f32,
        lockout: f32,
    },
    /// Taunt: caster's threat is raised to the top and the enemy attacks them.
    Taunt {
        duration: f32,
    },
    /// Self buff reducing damage taken by `pct` for `duration` seconds.
    DamageReduction {
        pct: f32,
        duration: f32,
    },
    /// Reduce caster's threat on every enemy by `pct`.
    ThreatDrop {
        pct: f32,
    },
    /// Interrupt the target's cast and lock out its spellcasting.
    Interrupt {
        lockout: f32,
        damage: f32,
    },
    /// Incapacitate a non-immune enemy; any damage breaks it.
    Incapacitate {
        duration: f32,
    },
    /// Remove one dispellable harmful effect from an ally.
    Dispel,
    /// Lab A: melee damage that gives Edge (more from behind the target).
    Builder {
        amount: f32,
        edge: u32,
        behind_edge: u32,
    },
    /// Lab A: spend all Edge on damage to every engaged enemy in `radius`.
    EdgeWhirl {
        base: f32,
        per_edge: f32,
        radius: f32,
    },
    /// Lab A: spend all Edge on a bleed (`per_edge` total per Edge).
    EdgeBleed {
        per_edge: f32,
        duration: f32,
    },
    /// Lab B: heavy hit on a target with an opening; consumes the opening and
    /// refunds energy if it lands. Flow also gains `edge` Edge.
    ExploitOpening {
        amount: f32,
        refund: f32,
        edge: u32,
    },
    /// Flow (0.11): spend all Edge (at least `min_edge`) on the target; with
    /// `splash_at` or more Edge, enemies within `splash_radius` of the target
    /// take `splash_frac` of it.
    Finisher {
        base: f32,
        per_edge: f32,
        min_edge: u32,
        splash_at: u32,
        splash_radius: f32,
        splash_frac: f32,
    },
}

