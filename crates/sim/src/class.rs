use crate::stats::{HitKind, School, Stats};
use serde::{Deserialize, Serialize};

pub const MAX_LEVEL: u32 = 10;

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum ClassId {
    /// Shield-bearing tank (rage).
    Warden,
    /// Healer (mana).
    Mender,
    /// Melee damage (energy).
    Striker,
    /// Ranged spell damage and control (mana).
    Arcanist,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum Role {
    Tank,
    Healer,
    MeleeDps,
    RangedDps,
}

impl Role {
    pub fn is_dps(self) -> bool {
        matches!(self, Role::MeleeDps | Role::RangedDps)
    }

    pub fn label(self) -> &'static str {
        match self {
            Role::Tank => "Tank",
            Role::Healer => "Healer",
            Role::MeleeDps => "Melee DPS",
            Role::RangedDps => "Ranged DPS",
        }
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub enum ResourceKind {
    /// Regenerates over time; five-second rule after spending.
    Mana,
    /// Starts empty; generated by dealing and taking damage; decays out of combat.
    Rage,
    /// Fixed regeneration of 10 per second up to 100.
    Energy,
}

impl ResourceKind {
    pub fn label(self) -> &'static str {
        match self {
            ResourceKind::Mana => "mana",
            ResourceKind::Rage => "rage",
            ResourceKind::Energy => "energy",
        }
    }
}

/// Class numbers at a given level (before equipment).
#[derive(Debug, Clone, Copy)]
pub struct ClassStats {
    pub max_hp: f32,
    pub resource: ResourceKind,
    pub max_resource: f32,
    pub speed: f32,
    pub attack_damage: f32,
    pub attack_interval: f32,
    /// Auto-attack reach (edge to edge).
    pub attack_range: f32,
    pub attack_kind: HitKind,
    pub attack_school: School,
    /// Multiplier on all threat generated.
    pub threat_mult: f32,
    /// Fraction of max mana regenerated per second when the five-second rule allows.
    pub mana_regen: f32,
    pub stats: Stats,
}

/// [orig] Damage and healing scale by +10% per level above 1.
pub fn level_power(level: u32) -> f32 {
    1.0 + 0.10 * (level.max(1) - 1) as f32
}

/// [orig] Health and mana scale by +12% per level above 1.
pub fn level_health(level: u32) -> f32 {
    1.0 + 0.12 * (level.max(1) - 1) as f32
}

